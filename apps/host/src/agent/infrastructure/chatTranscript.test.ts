import { appendFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { ChatTranscripts } from './chatTranscript.js';

const scratch: string[] = [];
afterEach(() => { for (const dir of scratch.splice(0)) rmSync(dir, { recursive: true, force: true }); });

const at = (minute: number) => new Date(Date.UTC(2026, 9, 21, 10, minute)).toISOString();
const line = (value: unknown) => `${JSON.stringify(value)}\n`;

describe('the chat read of an agent conversation', () => {
    it('turns a Claude log and a Pi log into whole messages, found the way Herdr names them, and only re-reads what moved', async () => {
        const root = mkdtempSync(join(tmpdir(), 'muxr-chat-'));
        scratch.push(root);
        const claude = join(root, 'claude', 'projects');
        const pi = join(root, 'pi', 'sessions');
        const cwd = '/home/you/little-shop';
        const folder = join(claude, '-home-you-little-shop');
        mkdirSync(folder, { recursive: true });
        mkdirSync(join(pi, '--home-you-little-shop--', 'run'), { recursive: true });

        writeFileSync(join(folder, 'abc-123.jsonl'), [
            line({ type: 'user', uuid: 'u1', timestamp: at(1), message: { role: 'user', content: 'Keep free shipping from $50.' } }),
            line({ type: 'user', uuid: 'u2', timestamp: at(1), isMeta: true, message: { role: 'user', content: 'Caveat: the messages below were generated by the user' } }),
            line({ type: 'user', uuid: 'u3', timestamp: at(1), message: { role: 'user', content: '<command-name>/clear</command-name>' } }),
            line({ type: 'user', uuid: 'u6', timestamp: at(1), message: { role: 'user', content: [{ type: 'text', text: '[Request interrupted by user for tool use]' }] } }),
            line({ type: 'user', uuid: 'u5', timestamp: at(1), origin: { kind: 'task-notification' }, message: { role: 'user', content: '<task-notification>done</task-notification>' } }),
            // One reply written once per content block, with a tool call in the middle.
            line({ type: 'assistant', uuid: 'a1', timestamp: at(2), message: { id: 'msg_1', role: 'assistant', content: [{ type: 'thinking', thinking: 'hmm' }, { type: 'text', text: 'Reading the cart code.' }] } }),
            line({ type: 'assistant', uuid: 'a2', timestamp: at(2), message: { id: 'msg_1', role: 'assistant', content: [{ type: 'tool_use', id: 'toolu_1', name: 'Read', input: { file_path: `${cwd}/src/cart.ts` } }] } }),
            line({ type: 'user', uuid: 'u4', timestamp: at(3), message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: 'toolu_1', content: '     1→export const FREE_FROM = 50;\n     2→export const FLAT = 5;' }] } }),
            line({ type: 'assistant', uuid: 'a3', timestamp: at(4), isSidechain: true, message: { id: 'msg_s', role: 'assistant', content: [{ type: 'text', text: 'a subagent talking to itself' }] } }),
            // A reply that only ran tools still shows, as its chips; an MCP tool reads by its own name.
            // Its edit carries the changed lines from its own arguments; the command its result's tail and exit code.
            line({ type: 'assistant', uuid: 'a5', timestamp: at(4), message: { id: 'msg_t', role: 'assistant', content: [
                { type: 'tool_use', id: 'toolu_2', name: 'Edit', input: { file_path: `${cwd}/src/cart.ts`, old_string: 'export function ship(t) {\n  if (t > FREE_FROM) return 0;\n  return FLAT;', new_string: 'export function ship(t) {\n  if (t >= FREE_FROM) return 0;\n  return FLAT;' } },
                { type: 'tool_use', id: 'toolu_3', name: 'Bash', input: { command: 'yarn test cart', description: 'Run the cart tests' } },
                { type: 'tool_use', name: 'mcp__shop__list_orders', input: {} },
            ] } }),
            // Claude Code's own patch beside an edit's result gives its real line numbers.
            line({ type: 'user', uuid: 'u7', timestamp: at(4), toolUseResult: { structuredPatch: [{ oldStart: 11, oldLines: 3, newStart: 11, newLines: 3, lines: [' export function ship(t) {', '-  if (t > FREE_FROM) return 0;', '+  if (t >= FREE_FROM) return 0;', '   return FLAT;'] }] }, message: { role: 'user', content: [
                { type: 'tool_result', tool_use_id: 'toolu_2', content: 'The file has been updated.' },
            ] } }),
            line({ type: 'user', uuid: 'u8', timestamp: at(4), message: { role: 'user', content: [
                { type: 'tool_result', tool_use_id: 'toolu_3', is_error: true, content: 'Exit code 1\nFAIL cart.test.ts\n  ✕ $50 ships free' },
            ] } }),
            line({ type: 'assistant', uuid: 'a4', timestamp: at(5), message: { id: 'msg_2', role: 'assistant', content: [{ type: 'text', text: 'Done. **4 tests** pass.' }] } }),
        ].join(''));
        writeFileSync(join(pi, '--home-you-little-shop--', 'run', '2026-10-21T10-00-00Z_pi-77.jsonl'), [
            line({ type: 'session', id: 'pi-77' }),
            line({ type: 'message', id: 'p1', timestamp: at(1), message: { role: 'user', timestamp: Date.parse(at(1)), content: [{ type: 'text', text: 'Check the empty cart.' }] } }),
            line({ type: 'message', id: 'p2', timestamp: at(2), message: { role: 'toolResult', content: [{ type: 'text', text: 'ls output' }] } }),
            line({ type: 'message', id: 'p3', timestamp: at(3), message: { role: 'assistant', timestamp: Date.parse(at(3)), content: [{ type: 'text', text: 'An empty cart ships free.' }, { type: 'toolCall', id: 'call_9', name: 'read', arguments: { path: 'cart.ts' } }] } }),
            line({ type: 'message', id: 'p4', timestamp: at(4), message: { role: 'toolResult', toolCallId: 'call_9', content: [{ type: 'text', text: 'export const FREE_FROM = 50;' }] } }),
        ].join(''));

        const chats = new ChatTranscripts(() => ({ claude: [claude], pi }));

        const first = await chats.read({ agent: 'claude', cwd, ref: { kind: 'id', value: 'abc-123' } });
        expect(first.state === 'ok' && first.messages.map((m) => [m.role, m.text, m.tools])).toEqual([
            ['user', 'Keep free shipping from $50.', undefined],
            ['assistant', 'Reading the cart code.', [{ verb: 'Read a file', kind: 'read', detail: 'src/cart.ts', outcome: 'ok', note: '2 lines', output: ['export const FREE_FROM = 50;', 'export const FLAT = 5;'] }]],
            ['assistant', '', [
                { verb: 'Edited a file', kind: 'edit', detail: 'src/cart.ts', diff: ['@@ -11 +11 @@', ' export function ship(t) {', '-  if (t > FREE_FROM) return 0;', '+  if (t >= FREE_FROM) return 0;', '   return FLAT;'], added: 1, removed: 1, outcome: 'ok' },
                { verb: 'Ran a command', kind: 'run', detail: 'yarn test cart', outcome: 'failed', exit: 1, output: ['FAIL cart.test.ts', '  ✕ $50 ships free'] },
                { verb: 'Used list orders', kind: 'tool' },
            ]],
            ['assistant', 'Done. **4 tests** pass.', undefined],
        ]);

        const piRead = await chats.read({ agent: 'pi', cwd, ref: { kind: 'id', value: 'pi-77' } });
        expect(piRead.state === 'ok' && piRead.messages.map((m) => [m.role, m.text, m.tools])).toEqual([
            ['user', 'Check the empty cart.', undefined],
            ['assistant', 'An empty cart ships free.', [{ verb: 'Read a file', kind: 'read', detail: 'cart.ts', outcome: 'ok', note: '1 line', output: ['export const FREE_FROM = 50;'] }]],
        ]);

        // Nothing moved: the phone's next poll costs one small answer.
        const revision = first.state === 'ok' ? first.revision : undefined;
        expect(await chats.read({ agent: 'claude', cwd, ref: { kind: 'id', value: 'abc-123' } }, revision)).toEqual({ state: 'unchanged' });
        appendFileSync(join(folder, 'abc-123.jsonl'), line({ type: 'user', uuid: 'u9', timestamp: at(6), message: { role: 'user', content: 'Ship it.' } }));
        const grown = await chats.read({ agent: 'claude', cwd, ref: { kind: 'id', value: 'abc-123' } }, revision);
        expect(grown.state === 'ok' && grown.messages.at(-1)?.text).toBe('Ship it.');

        // Agents with no chat, no conversation yet, and a path outside the harness's own logs.
        expect(await chats.read({ agent: 'codex', cwd, ref: { kind: 'id', value: 'x' } })).toEqual({ state: 'unavailable', reason: 'unsupported-agent' });
        expect(await chats.read({ agent: 'claude', cwd, ref: { kind: 'id', value: 'not-written-yet' } })).toEqual({ state: 'unavailable', reason: 'no-conversation' });
        const stray = join(root, 'stray.jsonl');
        writeFileSync(stray, line({ type: 'user', uuid: 's', timestamp: at(1), message: { role: 'user', content: 'private' } }));
        expect(await chats.read({ agent: 'claude', cwd, ref: { kind: 'path', value: stray } })).toEqual({ state: 'unavailable', reason: 'no-conversation' });
        expect(await chats.read({ agent: 'claude', cwd, ref: { kind: 'id', value: '../../stray' } })).toEqual({ state: 'unavailable', reason: 'no-conversation' });
    });

    it('shows the images of a conversation: pasted, returned by a tool, and files a reply names, each fetched on its own', async () => {
        const root = mkdtempSync(join(tmpdir(), 'muxr-chat-'));
        scratch.push(root);
        const claude = join(root, 'claude', 'projects');
        const pi = join(root, 'pi', 'sessions');
        const cwd = join(root, 'little-shop');
        const folder = join(claude, cwd.replace(/[^A-Za-z0-9]/g, '-'));
        mkdirSync(folder, { recursive: true });
        mkdirSync(join(cwd, 'shots'), { recursive: true });
        mkdirSync(join(pi, 'run'), { recursive: true });
        const png = Buffer.from('89504e470d0a1a0a0000000d49484452', 'hex');
        writeFileSync(join(cwd, 'shots', 'cart.png'), png);
        const pasted = { type: 'image', source: { type: 'base64', media_type: 'image/png', data: 'cGFzdGVk' } };

        writeFileSync(join(folder, 'img-1.jsonl'), [
            line({ type: 'user', uuid: 'u1', timestamp: at(1), message: { role: 'user', content: [{ type: 'text', text: '[Image #1] The cart looks off.' }, pasted] } }),
            line({ type: 'assistant', uuid: 'a1', timestamp: at(2), message: { id: 'msg_1', role: 'assistant', content: [{ type: 'tool_use', id: 'toolu_1', name: 'Read', input: { file_path: `${cwd}/shots/before.png` } }] } }),
            line({ type: 'user', uuid: 'u2', timestamp: at(2), message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: 'toolu_1', content: [{ type: 'image', source: { type: 'base64', media_type: 'image/png', data: 'YmVmb3Jl' } }] }] } }),
            line({ type: 'assistant', uuid: 'a2', timestamp: at(3), message: { id: 'msg_2', role: 'assistant', content: [{ type: 'text', text: 'Here is the page after the fix:\n\n![cart](shots/cart.png)\n\nThe old one was `shots/gone.png`.' }] } }),
        ].join(''));
        writeFileSync(join(pi, 'run', '2026-10-21T10-00-00Z_pi-8.jsonl'), [
            line({ type: 'message', id: 'p1', timestamp: at(1), message: { role: 'assistant', timestamp: Date.parse(at(1)), content: [{ type: 'toolCall', id: 'call_1', name: 'read', arguments: { path: 'shot.webp' } }] } }),
            line({ type: 'message', id: 'p2', timestamp: at(2), message: { role: 'toolResult', toolCallId: 'call_1', content: [{ type: 'image', data: 'cGk=', mimeType: 'image/webp' }] } }),
        ].join(''));

        const conversation = { agent: 'claude', cwd, ref: { kind: 'id' as const, value: 'img-1' } };
        const read = await new ChatTranscripts(() => ({ claude: [claude], pi })).read(conversation);
        expect(read.state === 'ok' && read.messages.map((m) => [m.text, m.images, m.tools?.[0]?.note])).toEqual([
            ['[Image #1] The cart looks off.', [{ id: 'u1.0', name: 'Image' }], undefined],
            ['', [{ id: 'toolu_1.0', name: 'Image' }], 'an image'],
            // The drawn image leaves the text for its own card; a named file that is not there shows nothing.
            ['Here is the page after the fix:\n\nThe old one was `shots/gone.png`.', [{ id: expect.stringMatching(/^f[0-9a-f]{16}$/), name: 'cart.png' }], undefined],
        ]);

        // A host that restarted since the phone read still finds each image by the id it gave.
        const chats = new ChatTranscripts(() => ({ claude: [claude], pi }));
        const fileId = read.state === 'ok' ? read.messages[2]!.images![0]!.id : '';
        expect(await chats.image(conversation, fileId)).toEqual({ mimeType: 'image/png', data: png.toString('base64') });
        expect(await chats.image(conversation, 'toolu_1.0')).toEqual({ mimeType: 'image/png', data: 'YmVmb3Jl' });
        expect(await chats.image(conversation, 'u1.0')).toEqual({ mimeType: 'image/png', data: 'cGFzdGVk' });
        expect(await chats.image(conversation, 'not-an-id')).toBeNull();
        expect(await chats.image({ agent: 'pi', cwd, ref: { kind: 'id', value: 'pi-8' } }, 'call_1.0')).toEqual({ mimeType: 'image/webp', data: 'cGk=' });
    });
});
